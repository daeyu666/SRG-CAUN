# train_drt_baseline_paper.py
"""Train DRT baseline with the DRT-Net paper data protocol and settings.

Paper protocol used here:
- HR-MSI is generated by uniformly selecting five bands from the reference HSI.
- LR-HSI is generated by 5x5 Gaussian blur with sigma=2 followed by 4x downsampling.
- The center 128x128 subregion is used for testing.
- Training crops are 128x128; pixels overlapping the center test region are zeroed.
- Training uses Adam, lr=1e-4, and 10000 epochs by default.

The model remains the no-innovation DRT baseline: no rectangular transformer,
no SAFA multiscale adaptive aggregation, and no contrastive learning.
"""

